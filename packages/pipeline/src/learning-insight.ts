/**
 * Learning insight — an optional, AI-generated narrative layered on top of
 * the rule-based learning loop (learning-loop.ts).
 *
 * PLAN §12 and the Learnings view are deliberately explicit that proposals
 * come from counting override rates against a fixed threshold, not from a
 * model: "not a vector database, and nothing here is summarized by a
 * model." This file does not change that — runLearningLoop() still decides
 * every proposed value, and nothing here can alter a Direction. What this
 * adds is a plain-language explanation of *why* the pattern the rules
 * found is happening, generated by the same Ollama (or other configured)
 * model already used for classify()/draft(), applied here to analysed
 * decision history instead of to a live signal.
 *
 * If no provider is configured, insight generation is skipped entirely —
 * proposals still work exactly as before, same fallback as classify/draft.
 */

import { describeModelError } from "./resilience.js";
import { aiConfigured, aiProvider, logger } from "@mind/core";
import type { DirectionProposal } from "./learning-loop.js";
import { generateReply } from "./model.js";

const SYSTEM = `You explain patterns in an attention-management system's decision history
to the operator who writes its rules. You are given a set of rule-based proposals,
each already backed by counted evidence (override rate, sample size). Your job is
only to explain, in plain language, what is likely driving the pattern — not to
second-guess the numbers, not to propose a different change, and not to invent
causes you cannot support from the evidence given. If the evidence is thin, say so.
Two to four sentences. No greeting, no sign-off, no bullet list.`;

function buildPrompt(proposals: DirectionProposal[]): string {
  const lines = proposals.map((p, i) => {
    const target = p.directionId ?? "(new direction)";
    return `${i + 1}. [${p.kind}] ${target} — ${p.field}: ${JSON.stringify(p.currentValue)} → ${JSON.stringify(p.proposedValue)}
   rationale: ${p.rationale}
   evidence: ${p.evidence.total} decided, ${p.evidence.discarded} discarded, ${p.evidence.sent} sent, override rate ${(p.evidence.overrideRate * 100).toFixed(0)}%`;
  });

  return `Here are this run's proposals:\n\n${lines.join("\n\n")}\n\nExplain what's likely driving this pattern across these proposals, for the operator deciding whether to accept them.`;
}

/**
 * Returns null when there is nothing to explain (no proposals) or no
 * provider is configured — same "degrade quietly" behaviour as classify/draft.
 */
export async function generateLearningInsight(
  proposals: DirectionProposal[],
): Promise<string | null> {
  if (proposals.length === 0) return null;
  if (!aiConfigured()) {
    logger.debug("learning-insight: no provider configured, skipping");
    return null;
  }

  try {
    const text = await generateReply({ system: SYSTEM, prompt: buildPrompt(proposals) });
    return text.length > 0 ? text : null;
  } catch (err) {
    logger.warn(
      { error: describeModelError(err), provider: aiProvider() },
      "learning-insight: LLM call failed",
    );
    return null;
  }
}
