/**
 * Model transport.
 *
 * HTTP providers go through the Vercel AI SDK (openai/anthropic/google plus
 * any OpenAI-compatible endpoint, including GitHub Copilot's). `kiro` and
 * `copilot-cli` have no HTTP model API and are driven over ACP.
 */

import { createAnthropic } from "@ai-sdk/anthropic";
import { createGoogleGenerativeAI } from "@ai-sdk/google";
import { createOpenAI } from "@ai-sdk/openai";
import { generateObject, generateText, type LanguageModel } from "ai";
import { z } from "zod";
import {
  aiBaseUrl,
  aiProvider,
  classifyModel,
  copilotIntegrationId,
  draftModel,
  isCliProvider,
  loadApiKey,
} from "@mind/core";
import { acpAgent, acpPrompt } from "./acp.js";

export interface ModelRequest {
  system: string;
  /** The full user prompt, already built by the caller. */
  prompt: string;
}

/** Classify: schema-validated object, generated by the fast model. */
export async function generateStructured<T>(
  schema: z.ZodType<T>,
  request: ModelRequest,
): Promise<T> {
  const model = classifyModel();
  if (isCliProvider()) {
    const text = await cliComplete(request, model, jsonHint(schema));
    return schema.parse(parseJson(text));
  }
  const { object } = await generateObject({
    model: await httpModel(model),
    schema,
    system: request.system,
    prompt: request.prompt,
  });
  return object as T;
}

/** Draft: plain reply text, generated by the larger model. */
export async function generateReply(request: ModelRequest): Promise<string> {
  const model = draftModel();
  if (isCliProvider()) return cliComplete(request, model);
  const { text } = await generateText({
    model: await httpModel(model),
    system: request.system,
    prompt: request.prompt,
  });
  return text.trim();
}

async function cliComplete(
  request: ModelRequest,
  model: string,
  hint = "",
): Promise<string> {
  return acpPrompt({
    agent: acpAgent(aiProvider()),
    cwd: process.cwd(),
    system: request.system,
    prompt: `${request.prompt}${hint}`,
    ...(model === "default" ? {} : { model }),
  });
}

async function httpModel(modelId: string): Promise<LanguageModel> {
  const provider = aiProvider();
  const key = loadApiKey();

  if (provider === "anthropic") {
    return createAnthropic({ apiKey: key ?? "" })(modelId);
  }
  if (provider === "google") {
    return createGoogleGenerativeAI({ apiKey: key ?? "" })(modelId);
  }

  const headers =
    provider === "copilot"
      ? {
          "Copilot-Integration-Id": copilotIntegrationId(),
          "Editor-Version": "mind/1.0.0",
        }
      : undefined;
  // `.chat()` pins the chat-completions endpoint; OpenAI-compatible servers
  // (Ollama, Copilot, custom gateways) do not implement the Responses API.
  return createOpenAI({
    apiKey: key ?? "local",
    baseURL: aiBaseUrl(),
    ...(headers ? { headers } : {}),
  }).chat(modelId);
}

/** ACP agents return prose; ask for one JSON object and validate it here. */
function jsonHint(schema: z.ZodType<unknown>): string {
  return `\n\nReturn only one JSON object, no prose or code fences, matching this JSON schema:\n${JSON.stringify(z.toJSONSchema(schema))}`;
}

/** Models sometimes wrap JSON in a fenced block; take the outermost object. */
function parseJson(text: string): unknown {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  const candidate =
    start >= 0 && end > start ? text.slice(start, end + 1) : text;
  return JSON.parse(candidate);
}
