/**
 * Model transport.
 *
 * HTTP providers go through the Vercel AI SDK (openai/anthropic/google plus
 * any OpenAI-compatible endpoint, including GitHub Copilot's). `kiro` and
 * `copilot-cli` have no HTTP model API and are driven over ACP.
 */

import { createAnthropic } from "@ai-sdk/anthropic";
import { createGoogleGenerativeAI } from "@ai-sdk/google";
import { createOpenAI } from "@ai-sdk/openai";
import { generateObject, generateText, type LanguageModel } from "ai";
import { z } from "zod";
import {
  aiBaseUrl,
  aiProvider,
  classifyModel,
  copilotIntegrationId,
  draftModel,
  isCliProvider,
  loadApiKey,
} from "@mind/core";
import { acpAgent, acpPrompt } from "./acp.js";

export interface ModelRequest {
  system: string;
  /** The full user prompt, already built by the caller. */
  prompt: string;
  /** Which pipeline step is calling, recorded in the trace. */
  operation?: ModelOperation;
  /** Characters of the message cut to fit the context window; recorded in the trace. */
  omittedChars?: number;
  /** Receives one trace per call, success or failure. Never carries prompt or response text. */
  onTrace?: (trace: ModelTrace) => void;
}

export type ModelOperation = "classify" | "draft" | "transform" | "link";

/**
 * What happened on one model call: enough to show that the call went to the
 * configured provider and how long it took. Deliberately excludes prompt and
 * response text, which are message content and do not belong in the audit log.
 */
export interface ModelTrace {
  operation: ModelOperation | "other";
  provider: string;
  model: string;
  transport: "http" | "acp";
  /** Base URL for HTTP providers (e.g. http://localhost:11434/v1); null for ACP agents. */
  endpoint: string | null;
  durationMs: number;
  ok: boolean;
  error?: string;
  promptChars: number;
  responseChars: number;
  /** Characters of the message left out so the prompt fit the model's context window. */
  omittedChars?: number;
  inputTokens?: number;
  outputTokens?: number;
}

interface TracedResult<T> {
  value: T;
  responseChars: number;
  inputTokens?: number | undefined;
  outputTokens?: number | undefined;
}

/** Runs one model call and reports a ModelTrace, then returns or rethrows unchanged. */
async function traced<T>(
  request: ModelRequest,
  model: string,
  call: () => Promise<TracedResult<T>>,
): Promise<T> {
  const cli = isCliProvider();
  const started = performance.now();
  const base = {
    operation: request.operation ?? ("other" as const),
    provider: aiProvider(),
    model,
    transport: cli ? ("acp" as const) : ("http" as const),
    endpoint: cli ? null : safeBaseUrl(),
    promptChars: request.system.length + request.prompt.length,
    ...(request.omittedChars ? { omittedChars: request.omittedChars } : {}),
  };
  try {
    const r = await call();
    request.onTrace?.({
      ...base,
      durationMs: Math.round(performance.now() - started),
      ok: true,
      responseChars: r.responseChars,
      ...(r.inputTokens !== undefined ? { inputTokens: r.inputTokens } : {}),
      ...(r.outputTokens !== undefined ? { outputTokens: r.outputTokens } : {}),
    });
    return r.value;
  } catch (err) {
    request.onTrace?.({
      ...base,
      durationMs: Math.round(performance.now() - started),
      ok: false,
      error: String(err instanceof Error ? err.message : err).slice(0, 300),
      responseChars: 0,
    });
    throw err;
  }
}

function safeBaseUrl(): string | null {
  try {
    return aiBaseUrl();
  } catch {
    return null;
  }
}

/** Classify: schema-validated object, generated by the fast model. */
export async function generateStructured<T>(
  schema: z.ZodType<T>,
  request: ModelRequest,
): Promise<T> {
  const model = classifyModel();
  return traced(request, model, async () => {
    if (isCliProvider()) {
      const text = await cliComplete(request, model, jsonHint(schema));
      return { value: schema.parse(parseJson(text)), responseChars: text.length };
    }
    const { object, usage } = await generateObject({
      model: await httpModel(model),
      schema,
      system: request.system,
      prompt: request.prompt,
    });
    return {
      value: object as T,
      responseChars: JSON.stringify(object).length,
      inputTokens: usage?.inputTokens,
      outputTokens: usage?.outputTokens,
    };
  });
}

/** Draft: plain reply text, generated by the larger model. */
export async function generateReply(request: ModelRequest): Promise<string> {
  const model = draftModel();
  return traced(request, model, async () => {
    if (isCliProvider()) {
      const text = await cliComplete(request, model);
      return { value: text, responseChars: text.length };
    }
    const { text, usage } = await generateText({
      model: await httpModel(model),
      system: request.system,
      prompt: request.prompt,
    });
    return {
      value: text.trim(),
      responseChars: text.length,
      inputTokens: usage?.inputTokens,
      outputTokens: usage?.outputTokens,
    };
  });
}

async function cliComplete(request: ModelRequest, model: string, hint = ""): Promise<string> {
  return acpPrompt({
    agent: acpAgent(aiProvider()),
    cwd: process.cwd(),
    system: request.system,
    prompt: `${request.prompt}${hint}`,
    ...(model === "default" ? {} : { model }),
  });
}

async function httpModel(modelId: string): Promise<LanguageModel> {
  const provider = aiProvider();
  const key = loadApiKey();

  if (provider === "anthropic") {
    return createAnthropic({ apiKey: key ?? "" })(modelId);
  }
  if (provider === "google") {
    return createGoogleGenerativeAI({ apiKey: key ?? "" })(modelId);
  }

  const headers =
    provider === "copilot"
      ? {
          "Copilot-Integration-Id": copilotIntegrationId(),
          "Editor-Version": "mind/1.0.0",
        }
      : undefined;
  // `.chat()` pins the chat-completions endpoint; OpenAI-compatible servers
  // (Ollama, Copilot, custom gateways) do not implement the Responses API.
  return createOpenAI({
    apiKey: key ?? "local",
    baseURL: aiBaseUrl(),
    ...(headers ? { headers } : {}),
  }).chat(modelId);
}

/** ACP agents return prose; ask for one JSON object and validate it here. */
function jsonHint(schema: z.ZodType<unknown>): string {
  return `\n\nReturn only one JSON object, no prose or code fences, matching this JSON schema:\n${JSON.stringify(z.toJSONSchema(schema))}`;
}

/** Models sometimes wrap JSON in a fenced block; take the outermost object. */
function parseJson(text: string): unknown {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  const candidate = start >= 0 && end > start ? text.slice(start, end + 1) : text;
  return JSON.parse(candidate);
}
